// Exercise the exact embedded diagnostic script without a browser or network.
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
import assert from 'node:assert/strict';
const source = readFileSync(new URL('../scripts/utilities/perf_ticker.gd', import.meta.url), 'utf8');
const script = source.match(/const BROWSER_CONTEXT_JS := """([\s\S]*?)"""/)[1];
const listeners = {};
const add = (key, fn) => (listeners[key] ??= []).push(fn);
let now = 0, focus = true;
const document = {hidden:false, hasFocus:()=>focus, addEventListener:add};
const window = {addEventListener:add};
const context = {window, document, performance:{now:()=>now}, JSON, Math};
runInNewContext(script, context);
const take = () => JSON.parse(window.__wwPerfContext());
assert.equal(take().hidden_ms, 0);
now = 100; document.hidden = true; listeners.visibilitychange[0]();
now = 5100; document.hidden = false; listeners.visibilitychange[0]();
now = 5200;
let result = take();
assert.equal(result.hidden_ms, 5000);
assert.equal(result.visibility_changes, 2);
assert.equal(result.visible, true);
assert.equal(result.window_ms, 5200);
assert.equal(take().hidden_ms, 0);
assert.equal(take().visibility_changes, 0);
focus = false; listeners.blur[0]();
assert.equal(take().focused, false);
listeners.focus[0]();
assert.equal(take().focus_changes, 1);
now = 5400;
listeners.pointerdown[0]({isTrusted:true, timeStamp:5250});
listeners.keydown[0]({isTrusted:false, timeStamp:0});
result = take();
assert.equal(result.inputs, 1);
assert.equal(result.event_delay_max_ms, 150);
assert.equal(take().event_delay_max_ms, 0);
runInNewContext(script, context);
assert.equal(listeners.visibilitychange.length, 1);
assert.equal(listeners.pointerdown.length, 1);
assert.equal(Object.keys(result).length, 9);
console.log('[perf-browser-context] 15 assertions passed');
